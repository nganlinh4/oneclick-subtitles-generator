vi.mock('@tauri-apps/api/core', () => ({ Channel: class {} }));

const CREDENTIAL_A = '01890f39-7b62-7c4e-8c9a-000000000301';
const CREDENTIAL_B = '01890f39-7b62-7c4e-8c9a-000000000302';
const REFERENCE_ID = '01890f39-7b62-7c4e-8c9a-000000000303';
const JOB_A = '01890f39-7b62-7c4e-8c9a-000000000304';
const JOB_B = '01890f39-7b62-7c4e-8c9a-000000000305';
const PROJECT_A = '01890f39-7b62-7c4e-8c9a-000000000306';
const PROJECT_B = '01890f39-7b62-7c4e-8c9a-000000000307';
const ARTIFACT_A = '01890f39-7b62-7c4e-8c9a-000000000308';
const ARTIFACT_B = '01890f39-7b62-7c4e-8c9a-000000000309';
const PLAYBACK_A = '4a8672f4-6e8f-4a16-8e4a-36b7d20fdb11';
const PLAYBACK_B = '9cb6df97-92c6-4f6d-8717-c2a7acb74a12';
const REFERENCE_PLAYBACK = 'c89ea814-1749-4c3b-8507-4c457df2ef30';
const TOKEN = 'a'.repeat(64);
const REFERENCE_PLAYBACK_URL = `http://127.0.0.1:43210/asset/${REFERENCE_PLAYBACK}?token=${TOKEN}`;

const snapshot = (id, state, sequence = 1) => ({
  id,
  kind: 'generateImage',
  state,
  progress: { basisPoints: state === 'succeeded' ? 10_000 : 0 },
  sequence,
});

const descriptor = (artifactId = ARTIFACT_A, projectId = PROJECT_A, mimeType = 'image/png') => ({
  artifactId,
  projectId,
  mimeType,
  sizeBytes: 4,
  createdAtMs: 1_700_000_000_000,
});

const playable = ({
  artifactId = ARTIFACT_A,
  projectId = PROJECT_A,
  playbackId = PLAYBACK_A,
  mimeType = 'image/png',
} = {}) => ({
  artifact: descriptor(artifactId, projectId, mimeType),
  playback: {
    id: playbackId,
    playbackUrl: `http://127.0.0.1:43210/asset/${playbackId}?token=${TOKEN}`,
    mimeType,
    byteLength: 4,
  },
});

class FakeChannel {
  onmessage = null;
}

const createHarness = ({
  invokeImplementation,
  importImageImplementation,
  resolveProjectImplementation,
  credentials = [CREDENTIAL_A],
} = {}) => {
  let activeIndex = 0;
  let activeCache = 'cache-a';
  const importImage = vi.fn(importImageImplementation ?? (async () => ({
    assetId: REFERENCE_ID,
    mimeType: 'image/png',
    sizeBytes: 16,
  })));
  const releaseImage = vi.fn().mockResolvedValue(true);
  const rotateCredential = vi.fn(async () => {
    activeIndex += 1;
  });
  const invokeCommand = vi.fn(invokeImplementation ?? (async (command, args) => {
    if (command === 'generated_image_playback_release') return true;
    if (command === 'gemini_image_complete') {
      return snapshot(args.request.jobId, 'succeeded', 2);
    }
    if (command !== 'gemini_image_start') throw new Error(`unexpected command ${command}`);
    queueMicrotask(() => {
      args.onEvent.onmessage({
        event: 'prepared',
        job: snapshot(JOB_A, 'running'),
        image: playable(),
      });
    });
    return snapshot(JOB_A, 'running');
  }));
  const cancel = vi.fn().mockResolvedValue(snapshot(JOB_A, 'cancelled', 2));
  const getCacheId = vi.fn(() => activeCache);
  const resolveProject = vi.fn(resolveProjectImplementation ?? (async (cacheId) => ({
    cacheId,
    projectId: cacheId === 'cache-a' ? PROJECT_A : PROJECT_B,
  })));
  const service = createNativeGeminiImage({
    prepareCredentials: vi.fn().mockResolvedValue(undefined),
    getCredentialId: vi.fn(() => credentials[activeIndex] ?? null),
    getCredentialSnapshot: vi.fn(() => ({
      gemini: { availableCredentialIds: credentials },
    })),
    rotateCredential,
    importImage,
    releaseImage,
    getCacheId,
    resolveProject,
    invokeCommand,
    ChannelConstructor: FakeChannel,
    cancel,
    isNativeRuntime: () => true,
  });
  return {
    service,
    importImage,
    releaseImage,
    rotateCredential,
    getCacheId,
    resolveProject,
    invokeCommand,
    cancel,
    setActiveProject: (projectId) => {
      activeCache = projectId === PROJECT_A ? 'cache-a' : 'cache-b';
    },
  };
};

test('returns only a project-owned artifact capability and never requests generated bytes', async () => {
  const harness = createHarness();
  const result = await harness.service.generate({
    referencePlaybackUrl: REFERENCE_PLAYBACK_URL,
    prompt: 'Expand this cover into a landscape image',
  });

  expect(result).toEqual({
    image: playable(),
    job: snapshot(JOB_A, 'succeeded', 2),
  });
  expect(harness.invokeCommand).toHaveBeenCalledWith('gemini_image_start', {
    request: {
      credentialId: CREDENTIAL_A,
      model: 'gemini-3.1-flash-image',
      prompt: expect.any(String),
      referenceAssetId: REFERENCE_ID,
      projectId: PROJECT_A,
    },
    onEvent: expect.any(FakeChannel),
  });
  expect(harness.invokeCommand).toHaveBeenCalledWith('gemini_image_complete', {
    request: {
      jobId: JOB_A,
      projectId: PROJECT_A,
      artifactId: ARTIFACT_A,
      playbackId: PLAYBACK_A,
    },
  });
  const serialized = JSON.stringify(result);
  expect(serialized).not.toMatch(/(?:base64|data:image|"bytes"|file:|[A-Za-z]:\\)/i);
  expect(harness.invokeCommand.mock.calls[0][1]).not.toHaveProperty('onImage');
  expect(harness.importImage).toHaveBeenCalledWith(REFERENCE_PLAYBACK_URL, PROJECT_A);
  expect(harness.releaseImage).toHaveBeenCalledWith(REFERENCE_ID);
});

test('rotates credentials only after a sanitized credential failure', async () => {
  let startCall = 0;
  const harness = createHarness({
    credentials: [CREDENTIAL_A, CREDENTIAL_B],
    invokeImplementation: async (command, args) => {
      if (command === 'generated_image_playback_release') return true;
      if (command === 'gemini_image_complete') {
        return snapshot(args.request.jobId, 'succeeded', 2);
      }
      if (command !== 'gemini_image_start') throw new Error(`unexpected command ${command}`);
      startCall += 1;
      const id = startCall === 1 ? JOB_A : JOB_B;
      queueMicrotask(() => {
        if (startCall === 1) {
          args.onEvent.onmessage({
            event: 'failed',
            job: snapshot(id, 'failed', 2),
            error: { code: 'geminiRateLimited', message: 'fixed host message' },
          });
        } else {
          args.onEvent.onmessage({
            event: 'prepared',
            job: snapshot(id, 'running'),
            image: playable(),
          });
        }
      });
      return snapshot(id, 'running');
    },
  });

  await expect(harness.service.generate({
    referencePlaybackUrl: REFERENCE_PLAYBACK_URL,
    prompt: 'Generate',
  })).resolves.toMatchObject({ image: playable() });
  expect(harness.rotateCredential).toHaveBeenCalledWith({
    cooldownCredentialId: CREDENTIAL_A,
  });
  expect(harness.invokeCommand.mock.calls[1][1].request.credentialId).toBe(CREDENTIAL_B);
});

