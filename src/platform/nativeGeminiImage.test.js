test('returns only a project-owned artifact capability and never requests generated bytes', async () => {
  const harness = createHarness();
  const result = await harness.service.generate({
    referencePlaybackUrl: REFERENCE_PLAYBACK_URL,
    prompt: 'Expand this cover into a landscape image',
  });

  expect(result).toEqual({
    image: playable(),
    job: snapshot(JOB_A, 'succeeded', 2),
  });
  expect(harness.invokeCommand).toHaveBeenCalledWith('gemini_image_start', {
    request: {
      credentialId: CREDENTIAL_A,
      model: 'gemini-3.1-flash-image',
      prompt: expect.any(String),
      referenceAssetId: REFERENCE_ID,
      projectId: PROJECT_A,
    },
    onEvent: expect.any(FakeChannel),
  });
  expect(harness.invokeCommand).toHaveBeenCalledWith('gemini_image_complete', {
    request: {
      jobId: JOB_A,
      projectId: PROJECT_A,
      artifactId: ARTIFACT_A,
      playbackId: PLAYBACK_A,
    },
  });
  const serialized = JSON.stringify(result);
  expect(serialized).not.toMatch(/(?:base64|data:image|"bytes"|file:|[A-Za-z]:\\)/i);
  expect(harness.invokeCommand.mock.calls[0][1]).not.toHaveProperty('onImage');
  expect(harness.importImage).toHaveBeenCalledWith(REFERENCE_PLAYBACK_URL, PROJECT_A);
  expect(harness.releaseImage).toHaveBeenCalledWith(REFERENCE_ID);
});

test('rotates credentials only after a sanitized credential failure', async () => {
  let startCall = 0;
  const harness = createHarness({
    credentials: [CREDENTIAL_A, CREDENTIAL_B],
    invokeImplementation: async (command, args) => {
      if (command === 'generated_image_playback_release') return true;
      if (command === 'gemini_image_complete') {
        return snapshot(args.request.jobId, 'succeeded', 2);
      }
      if (command !== 'gemini_image_start') throw new Error(`unexpected command ${command}`);
      startCall += 1;
      const id = startCall === 1 ? JOB_A : JOB_B;
      queueMicrotask(() => {
        if (startCall === 1) {
          args.onEvent.onmessage({
            event: 'failed',
            job: snapshot(id, 'failed', 2),
            error: { code: 'geminiRateLimited', message: 'fixed host message' },
          });
        } else {
          args.onEvent.onmessage({
            event: 'prepared',
            job: snapshot(id, 'running'),
            image: playable(),
          });
        }
      });
      return snapshot(id, 'running');
    },
  });

  await expect(harness.service.generate({
    referencePlaybackUrl: REFERENCE_PLAYBACK_URL,
    prompt: 'Generate',
  })).resolves.toMatchObject({ image: playable() });
  expect(harness.rotateCredential).toHaveBeenCalledWith({
    cooldownCredentialId: CREDENTIAL_A,
  });
  expect(harness.invokeCommand.mock.calls[1][1].request.credentialId).toBe(CREDENTIAL_B);
});

