test('a pre-aborted request performs no project lookup, import, or native invocation', async () => {
  const harness = createHarness();
  const controller = new AbortController();
  controller.abort();

  await expect(harness.service.generate({
    referencePlaybackUrl: REFERENCE_PLAYBACK_URL,
    prompt: 'Generate',
    signal: controller.signal,
  })).rejects.toMatchObject({ name: 'AbortError' });
  expect(harness.getCacheId).not.toHaveBeenCalled();
  expect(harness.importImage).not.toHaveBeenCalled();
  expect(harness.invokeCommand).not.toHaveBeenCalled();
});

test('a project switch during native reference transfer releases the imported reference', async () => {
  let resolveImport;
  const harness = createHarness({
    importImageImplementation: () => new Promise((resolve) => {
      resolveImport = resolve;
    }),
  });
  const generation = harness.service.generate({
    referencePlaybackUrl: REFERENCE_PLAYBACK_URL,
    prompt: 'Generate',
  });
  await vi.waitFor(() => expect(resolveImport).toBeTypeOf('function'));
  harness.setActiveProject(PROJECT_B);
  resolveImport({ assetId: REFERENCE_ID, mimeType: 'image/png', sizeBytes: 16 });

  await expect(generation).rejects.toMatchObject({ code: 'staleGeminiImageProject' });
  expect(harness.releaseImage).toHaveBeenCalledWith(REFERENCE_ID);
  expect(harness.invokeCommand).not.toHaveBeenCalled();
});
