test('list resolve export delete clear and release use only bounded opaque identities', async () => {
  const calls = [];
  const harness = createHarness({
    invokeImplementation: async (command, args) => {
      calls.push([command, args]);
      if (command === 'generated_image_list') {
        return [descriptor(ARTIFACT_A), descriptor(ARTIFACT_B)];
      }
      if (command === 'generated_image_resolve') {
        return args.request.artifactId === ARTIFACT_A
          ? playable()
          : playable({ artifactId: ARTIFACT_B, playbackId: PLAYBACK_B });
      }
      if (command === 'generated_image_export') return true;
      if (command === 'generated_image_delete') return true;
      if (command === 'generated_image_clear') return 2;
      if (command === 'generated_image_playback_release') return true;
      throw new Error('unexpected command');
    },
  });

  const loaded = await harness.service.load(PROJECT_A);
  expect(loaded).toHaveLength(2);
  await expect(harness.service.exportImage({
    projectId: PROJECT_A,
    artifactId: ARTIFACT_A,
    suggestedName: 'background-1.png',
  })).resolves.toBe(true);
  await expect(harness.service.deleteImage({
    projectId: PROJECT_A,
    artifactId: ARTIFACT_A,
  })).resolves.toBe(true);
  await expect(harness.service.clear(PROJECT_A)).resolves.toBe(2);
  await expect(harness.service.releasePlayback(loaded[0])).resolves.toBe(true);

  expect(JSON.stringify(calls)).not.toMatch(/(?:base64|data:image|"bytes"|file:|[A-Za-z]:\\)/i);
});

