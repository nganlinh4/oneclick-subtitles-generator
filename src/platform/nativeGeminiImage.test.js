test('list resolve export delete clear and release use only bounded opaque identities', async () => {
  const calls = [];
  const harness = createHarness({
    invokeImplementation: async (command, args) => {
      calls.push([command, args]);
      if (command === 'generated_image_list') {
        return [descriptor(ARTIFACT_A), descriptor(ARTIFACT_B)];
      }
      if (command === 'generated_image_resolve') {
        return args.request.artifactId === ARTIFACT_A
          ? playable()
          : playable({ artifactId: ARTIFACT_B, playbackId: PLAYBACK_B });
      }
      if (command === 'generated_image_export') return true;
      if (command === 'generated_image_delete') return true;
      if (command === 'generated_image_clear') return 2;
      if (command === 'generated_image_playback_release') return true;
      throw new Error('unexpected command');
    },
  });

  const loaded = await harness.service.load(PROJECT_A);
  expect(loaded).toHaveLength(2);
  await expect(harness.service.exportImage({
    projectId: PROJECT_A,
    artifactId: ARTIFACT_A,
    suggestedName: 'background-1.png',
  })).resolves.toBe(true);
  await expect(harness.service.deleteImage({
    projectId: PROJECT_A,
    artifactId: ARTIFACT_A,
  })).resolves.toBe(true);
  await expect(harness.service.clear(PROJECT_A)).resolves.toBe(2);
  await expect(harness.service.releasePlayback(loaded[0])).resolves.toBe(true);

  expect(JSON.stringify(calls)).not.toMatch(/(?:base64|data:image|"bytes"|file:|[A-Za-z]:\\)/i);
});

test('stale rendered project identities cannot export delete or clear another active project', async () => {
  const harness = createHarness();
  harness.setActiveProject(PROJECT_B);

  await expect(harness.service.exportImage({
    projectId: PROJECT_A,
    artifactId: ARTIFACT_A,
    suggestedName: 'background-1.png',
  })).rejects.toMatchObject({ code: 'staleGeminiImageProject' });
  await expect(harness.service.deleteImage({
    projectId: PROJECT_A,
    artifactId: ARTIFACT_A,
  })).rejects.toMatchObject({ code: 'staleGeminiImageProject' });
  await expect(harness.service.clear(PROJECT_A))
    .rejects.toMatchObject({ code: 'staleGeminiImageProject' });

  expect(harness.invokeCommand.mock.calls.filter(([command]) => [
    'generated_image_export',
    'generated_image_delete',
    'generated_image_clear',
  ].includes(command))).toHaveLength(0);
  await expect(harness.service.releasePlayback(playable())).resolves.toBe(true);
  expect(harness.invokeCommand).toHaveBeenCalledWith('generated_image_playback_release', {
    request: {
      projectId: PROJECT_A,
      artifactId: ARTIFACT_A,
      playbackId: PLAYBACK_A,
    },
  });
});

test.each([
  [
    'export',
    (service) => service.exportImage({
      projectId: PROJECT_A,
      artifactId: ARTIFACT_A,
      suggestedName: 'background-1.png',
    }),
    'generated_image_export',
  ],
  [
    'delete',
    (service) => service.deleteImage({ projectId: PROJECT_A, artifactId: ARTIFACT_A }),
    'generated_image_delete',
  ],
  ['clear', (service) => service.clear(PROJECT_A), 'generated_image_clear'],
])('a cache A to B switch during awaited project resolution blocks %s IPC', async (
  _operation,
  runMutation,
  forbiddenCommand
) => {
  let resolveLookup;
  const harness = createHarness({
    resolveProjectImplementation: (cacheId) => new Promise((resolve) => {
      resolveLookup = () => resolve({ cacheId, projectId: PROJECT_A });
    }),
  });

  const mutation = runMutation(harness.service);
  await vi.waitFor(() => expect(resolveLookup).toBeTypeOf('function'));
  harness.setActiveProject(PROJECT_B);
  resolveLookup();

  await expect(mutation).rejects.toMatchObject({ code: 'staleGeminiImageProject' });
  expect(harness.invokeCommand.mock.calls.some(([command]) => command === forbiddenCommand))
    .toBe(false);
});

test('the cache is reread synchronously immediately before destructive IPC', async () => {
  const getCacheId = vi.fn()
    .mockReturnValueOnce('cache-a')
    .mockReturnValueOnce('cache-a')
    .mockReturnValue('cache-b');
  const invokeCommand = vi.fn();
  const service = createNativeGeminiImage({
    getCacheId,
    resolveProject: vi.fn().mockResolvedValue({ cacheId: 'cache-a', projectId: PROJECT_A }),
    invokeCommand,
    isNativeRuntime: () => true,
  });

  await expect(service.deleteImage({
    projectId: PROJECT_A,
    artifactId: ARTIFACT_A,
  })).rejects.toMatchObject({ code: 'staleGeminiImageProject' });
  expect(invokeCommand).not.toHaveBeenCalled();
  expect(getCacheId).toHaveBeenCalledTimes(3);
});

